"""
shared/zhkh_parser.py — Парсер писем-обращений через ГИС ЖКХ (рассылка ТГК-11).

Поддерживает несколько исторических форматов тела письма:
  1) Старый табличный «Информация о заявителе»: Фамилия/Имя/Отчество раздельно,
     разделитель — таб.
  2) Блочный (июнь 2026): label на своей строке, пустая строка, значение
     на следующей («Фамилия\\n\\nАрнгольд\\n\\n»).
  3) Колон-табличный v1 (конец июня): «Заявитель:\\t<ФИО>\\t», лейблы
     «Тема» / «Адрес» / «Email заявителя» / «Срок исполнения».
  4) Колон-табличный v2 (текущий): ФИО в секции «Заявитель» под лейблом
     «ФИО:», лейблы «Тема обращения» / «Адрес дома/территории» / «Email» /
     «Планируемая дата исполнения» + «Крайний срок исполнения».

Форматы 3 и 4 разбираются единым _parse_new_format() — он пробует
оба набора лейблов (новый → старый) для каждого поля.

Если body не совпадает ни с одним шаблоном — возвращается None.
"""

import re
import logging

log = logging.getLogger("asud.zhkh")

# Маркер старого/блочного формата (1/2): заголовок «Информация о заявителе»
_ZHKH_MARKER = "Информация о заявителе"

# Маркеры колон-табличных форматов (3/4). Любой + отсутствие старого маркера.
_NEW_MARKERS = ("Номер обращения:", "Текст обращения", "Заявитель", "Адрес дома/территории:")

# Значения которые считаем «пусто».
_EMPTY_VALUES = ('информация не указана', '-', '—', 'нет', 'не определена',
                 'не определен', 'не назначен', 'не назначена')

# Шаблоны раскладки полей:
#   BLOCK — label / пустая строка / значение
#   TAB   — «Label\t Value\t» (несколько полей на строке)
#   COLON — «Label:\t Value\t» (форматы 3/4, лейбл с двоеточием)
_BLOCK_RE_TEMPLATE = r'(?ms)^\s*{label}\s*\r?\n\s*\r?\n\s*([^\r\n]+?)\s*\r?$'
_TAB_RE_TEMPLATE   = r'(?m)(?:(?<=\t)|^)\s*{label}\s*\t\s*([^\t\r\n]+?)\s*(?=\t|\r|\n|$)'
_COLON_RE_TEMPLATE = r'(?m)^\s*{label}\s*:\s*\t?\s*([^\t\r\n]+?)\s*(?=\t|\r|\n|$)'


def _find_field(body, label, templates=None):
    """Ищет значение поля по названию. Пробует переданные шаблоны по очереди."""
    if templates is None:
        templates = (_BLOCK_RE_TEMPLATE, _TAB_RE_TEMPLATE)
    for tmpl in templates:
        pat = tmpl.replace('{label}', re.escape(label))
        m = re.search(pat, body)
        if m:
            val = m.group(1).strip()
            if val and val.lower() not in _EMPTY_VALUES:
                return val
    return None


def _find_first(body, labels, templates):
    """Возвращает первое непустое значение из списка лейблов (по приоритету)."""
    for label in labels:
        v = _find_field(body, label, templates=templates)
        if v:
            return v
    return None


def _date_only(val):
    """Из «21.07.2026 23:59 (осталось 22 дн.)» → «21.07.2026».
    Если даты в начале нет — None."""
    if not val:
        return None
    m = re.match(r'\s*(\d{2}\.\d{2}\.\d{4})', val)
    return m.group(1) if m else None


def _parse_new_format(body):
    """Форматы 3/4: колон-табличные. ФИО одним полем.
    Возвращает dict или None.

    Для анонимных писем (поля ФИО/Заявитель нет) фио=None — вызывающий код
    подставит «Неизвестный», остальные поля (номер/тема/адрес) используются.
    """
    C = (_COLON_RE_TEMPLATE,)
    num = _find_field(body, 'Номер обращения', templates=C)
    if not num:
        return None  # без номера это не ГИС ЖКХ нового формата

    # Контакты заявителя (ФИО/Email/Телефон) ищем ТОЛЬКО в секции заявителя —
    # до блока «Получатель (организация)». Иначе «Телефон:» подцепит телефон
    # организации (+7(3812)945277) если у заявителя телефон не указан.
    applicant = body
    cut = body.find('Получатель (организация)')
    if cut != -1:
        applicant = body[:cut]

    # ФИО: формат 4 — «ФИО:», формат 3 — «Заявитель:»
    fio = _find_first(applicant, ('ФИО', 'Заявитель'), C)

    # Планируемая дата: приоритет «Планируемая дата исполнения», затем
    # «Крайний срок исполнения», затем «Срок исполнения» (формат 3).
    # Каждое значение чистим до DD.MM.YYYY (срезаем время и «(осталось N дн.)»).
    plan_raw = _find_first(body, ('Планируемая дата исполнения',
                                   'Крайний срок исполнения',
                                   'Срок исполнения'), C)
    plan = _date_only(plan_raw)

    return {
        'фамилия':         (fio.split()[0] if fio else None),
        'имя':             (fio.split()[1] if fio and len(fio.split()) > 1 else None),
        'отчество':        (fio.split()[2] if fio and len(fio.split()) > 2 else None),
        'фио':             fio,  # None для анонимных — caller подставит «Неизвестный»
        'номер_обращения': num,
        # Дата получения часто с временем («29.06.2026 15:36») — режем до
        # DD.MM.YYYY: иначе поле «Дата у корреспондента» в АСУД отвергает
        # значение со временем и остаётся пустым → регистрация падает.
        'дата_обращения':  _date_only(_find_field(body, 'Дата получения', templates=C)),
        'планируемая_дата': plan,
        'тема_обращения':  _find_first(body, ('Тема обращения', 'Тема'), C),
        'адрес':           _find_first(body, ('Адрес дома/территории', 'Адрес'), C),
        'телефон':         _find_field(applicant, 'Телефон', templates=C),  # только из секции заявителя
        'email':           _find_first(applicant, ('Email', 'Email заявителя', 'E-mail'), C),
    }


def parse_zhkh_body(body):
    """Парсит body-обращение ГИС ЖКХ. Возвращает dict или None.

    Структура dict:
      {
        'фамилия': '...', 'имя': '...', 'отчество': '...',
        'фио':             'Перевалова Анастасия Александровна',  # None если аноним
        'номер_обращения': '55-2026-41171',
        'дата_обращения':  '29.06.2026',
        'планируемая_дата': '21.07.2026',  # из План/Крайний срок, опционально
        'тема_обращения':  '...', 'адрес': '...', 'телефон': '...', 'email': '...',
      }

    None если body не похоже ни на один ГИС ЖКХ-формат.
    """
    if not body:
        return None

    # Формат 1/2 — маркер «Информация о заявителе», ФИО раздельно.
    # NB: при неудаче НЕ возвращаем None сразу, а проваливаемся в формат 3/4.
    # Иначе письмо 4-го формата, где в ТЕКСТЕ жалобы случайно встретилась
    # фраза «Информация о заявителе», ушло бы сюда, не нашло «Фамилия» и
    # потерялось бы (return None → общий extractor → мусор).
    if _ZHKH_MARKER in body:
        surname = _find_field(body, 'Фамилия')
        name = _find_field(body, 'Имя')
        patronymic = _find_field(body, 'Отчество')
        parts = [p for p in (surname, name, patronymic) if p]
        if len(parts) >= 2:
            return {
                'фамилия':         surname,
                'имя':             name,
                'отчество':        patronymic,
                'фио':             ' '.join(parts),
                'номер_обращения': _find_field(body, 'Номер обращения'),
                'дата_обращения':  _find_field(body, 'Дата получения обращения'),
                'планируемая_дата': _find_field(body, 'Планируемая дата исполнения'),
                'тема_обращения':  _find_field(body, 'Тема обращения'),
                'адрес':           _find_field(body, 'Адрес дома/территории'),
                'телефон':         _find_field(body, 'Номер телефона'),
                'email':           _find_field(body, 'E-mail'),
            }
        log.debug(f"ZHKH (формат 1/2): не хватает ФИО-частей "
                  f"({surname=!r} {name=!r} {patronymic=!r}) — пробую формат 3/4")
        # провал в формат 3/4 ниже (не return None)

    # Форматы 3/4 — колон-табличные
    if any(m in body for m in _NEW_MARKERS):
        result = _parse_new_format(body)
        if result:
            log.debug(f"ZHKH (формат 3/4): фио={result.get('фио')!r}, "
                      f"№{result.get('номер_обращения')}, "
                      f"план={result.get('планируемая_дата')}")
            return result

    return None
